/****************************************************************************
 * Silver Guardian Hub - 板间联动接口（Hub 侧接收端）
 *
 * 手环端（另一块板子）通过 WiFi 往 Hub 发一行一条的 ASCII 报文，
 * Hub 收到后翻译成事件系统里的事件，走和"本机触发"完全一样的通路：
 * 提示音 + 屏幕警示层 + 指示灯 + 事件记录。
 *
 * 协议（一行一条，\n 结尾，UDP 到 Hub 的 5555 端口）
 * ---------------------------------------------------------------------------
 *   SG1 SOS                    老人按下呼救键      -> 紧急求助（红快闪 + 警示层）
 *   SG1 SOS_CANCEL             取消呼救            -> 收起告警
 *   SG1 SITTING <秒>           手环判定久坐        -> 久坐提醒
 *   SG1 RESUMED                恢复活动            -> 收起告警
 *   SG1 FALL                   跌倒检测            -> 按 SOS 处理
 *   SG1 HB                     心跳，每 10 秒一条   -> 只更新"手环在线"状态
 *   SG1 IMU <x> <y> <z>        原始加速度，预留    -> 当前只记日志
 *
 * 带 `SG1 ` 前缀是为了把协议版本写死在报文里，以后加字段不至于认错。
 * 认不出的行会被丢弃并记一条日志，不会影响 Hub 运行。
 *
 * 端口/前缀都定义在下面，手环端对着这个头文件实现即可。
 ****************************************************************************/

#ifndef __APP_SILVER_GUARDIAN_HUB_INCLUDE_LINK_H
#define __APP_SILVER_GUARDIAN_HUB_INCLUDE_LINK_H

/****************************************************************************
 * Included Files
 ****************************************************************************/

#include <nuttx/config.h>
#include <stdbool.h>
#include <stdint.h>

/****************************************************************************
 * Pre-processor Definitions
 ****************************************************************************/

/* 板间联动的约定 —— 手环端按这几个值实现 */

#define SG_LINK_PORT        5555     /* Hub 监听的 UDP 端口 */
#define SG_LINK_PREFIX      "SG1 "   /* 每条报文的定长前缀 */
#define SG_LINK_LINE_MAX    128      /* 单条报文最长字节数 */

/* 心跳丢失多久算手环离线 */

#define SG_LINK_PEER_TIMEOUT_MS  (30 * 1000)

/****************************************************************************
 * Public Types
 ****************************************************************************/

typedef struct
{
  bool     opened;        /* 监听 socket 是否建好 */
  int      err;           /* 建立失败时的 errno */
  uint32_t rx_lines;      /* 累计收到的合法报文数 */
  uint32_t rx_dropped;    /* 累计丢弃（队列满 / 格式错） */
  uint32_t last_rx_ms;    /* 最近一次收到报文的时刻 */
  bool     peer_online;   /* 手环是否在线（心跳未超时） */
} sg_link_diag_t;

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/**
 * @brief 起监听：建 UDP socket + 收包线程
 * @return 0 成功，负 errno 失败（失败不致命，只是没有板间联动）
 */

int sg_link_init(void);

/**
 * @brief 关闭监听
 */

void sg_link_deinit(void);

/**
 * @brief 主循环调用：把收到的报文翻译成事件分发出去
 *
 * 收包在独立线程里做，但**事件的产生放在主循环**——
 * event_send() 操作的是全局队列，没有加锁，多线程写会坏。
 * 所以线程只负责收+入队，主循环负责出队+翻译成事件。
 */

void sg_link_poll(void);

/**
 * @brief 取自检状态
 */

const sg_link_diag_t *sg_link_get_diag(void);

#endif /* __APP_SILVER_GUARDIAN_HUB_INCLUDE_LINK_H */
