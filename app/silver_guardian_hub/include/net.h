/****************************************************************************
 * Silver Guardian Hub - 网络状态头文件
 *
 * 为什么单独有这个模块：cloud.c 是本地桩，里面 `wifi_connected = true` 是
 * **硬编码**的（当初占位用），状态栏读的就是它 —— 结果不管有没有网都显示
 * "已联网"。这个模块负责回答"到底连上没有"，答案来自网络栈本身。
 ****************************************************************************/

#ifndef __APP_SILVER_GUARDIAN_HUB_INCLUDE_NET_H
#define __APP_SILVER_GUARDIAN_HUB_INCLUDE_NET_H

/****************************************************************************
 * Included Files
 ****************************************************************************/

#include <nuttx/config.h>
#include <stdbool.h>

/****************************************************************************
 * Pre-processor Definitions
 ****************************************************************************/

/* WiFi 接口名（板级 realtek 驱动注册的就是这个） */

#define SG_NET_IFNAME "wlan0"

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/**
 * @brief wlan0 是否真的可用
 *
 * 判据是"分到了非 0 的 IPv4 地址**且**链路 RUNNING"——只关联上但没拿到
 * IP 是不通的，只看到 IP 而链路掉了同样不通。
 *
 * @return true 可用
 */

bool sg_net_wifi_connected(void);

#endif /* __APP_SILVER_GUARDIAN_HUB_INCLUDE_NET_H */
